use crate::model::TrackId;

/// 运行时传输命令（不属于可撤销的工程编辑）。
///
/// 绝大多数字段是 `Copy` 标量：这些命令会经由无锁 SPSC 队列进入音频回调。
/// `SetParam` 的参数名与 `SetAutomation` 的目标是所有权字段——都在控制侧分配妥当，实时侧只做移动。
#[derive(Debug, Clone, PartialEq)]
pub enum TransportCommand {
    /// 开始或恢复播放。
    Play,
    /// 暂停并保留当前位置。
    Pause,
    /// 停止并回到起点。
    Stop,
    /// 定位到指定帧。
    Seek { frame: u64 },
    /// 实时更新某轨的混音参数。
    ///
    /// 单独设立（而不是重建整张事件表）的原因是：拖动推子会以每秒数十次的频率产生
    /// 参数变化，重建播放器会不断重置插件状态并造成音频中断。
    SetTrackMix {
        /// 目标轨道。
        track: TrackId,
        /// 增益（dB）。
        gain_db: f32,
        /// 声像（-1.0 最左，1.0 最右）。
        pan: f32,
        /// 是否静音。
        mute: bool,
        /// 是否独奏。
        solo: bool,
    },
    /// 实时更新总输出增益（dB）。
    SetMasterGain { gain_db: f32 },
    /// 界面上按下的**试听音**：直接送给某条轨道的乐器，不写进工程。
    ///
    /// 这是「合成器界面上的键盘」那条路径——试听不该产生可撤销的编辑，也不该等传输。
    Audition {
        /// 目标轨道。
        track: TrackId,
        /// MIDI 音高。
        note: u8,
        /// 力度（0..=127）；松开时忽略。
        velocity: u8,
        /// `true` 按下，`false` 松开。
        on: bool,
    },
    /// 实时更新某个插件的参数——直接作用于已装载的实例，**不重建播放器**。
    ///
    /// 与 [`Self::SetTrackMix`] 同理：插件界面上的旋钮会高频产生参数变化，重建播放器
    /// 会不断重置插件状态并造成音频中断。
    SetParam {
        /// 目标轨道。
        track: TrackId,
        /// `None` = 轨道乐器；`Some(i)` = 效果链第 `i` 个。
        effect: Option<usize>,
        /// 参数标识（插件自报的 `params()` 里的 id）。
        param: String,
        /// 目标值。
        value: f32,
    },
    /// 开关循环播放：播到工程结尾无缝回到起点继续。属于运行时传输状态，不写入工程。
    SetLoop(bool),
    /// 设定**播放范围**（cycle range）：开了循环时，播到 `end` 就无缝回到 `start` 继续。
    ///
    /// `end <= start` = 取消范围（回到「整首循环」的行为）。单位是**帧**，`start` 是工程
    /// 时间轴上的绝对帧号。范围只决定「回卷到哪里」，是否真的回卷仍由 [`Self::SetLoop`]
    /// 决定——关掉循环时范围不生效（照旧播到工程结尾停住）。
    ///
    /// 属于运行时传输状态，不写入工程。
    SetLoopRange {
        /// 回卷目标帧（区间起点）。
        start: u64,
        /// 触发回卷的帧（区间终点）。
        end: u64,
    },
    /// 开关**节拍器**：按工程速度 / 拍号在整数拍上打点（重音在小节头）。
    ///
    /// 属于运行时传输状态，不写入工程；只在播放时出声。
    SetMetronome(bool),
    /// 实时更新一条自动化车道（`points` 为空 = 删除该车道）。
    ///
    /// 自动化是「仅混音」变更：不重建播放器，只把新曲线推给音频线程，逐块求值。
    ///
    /// `target` 是**控制侧解析好的**目标（`schedule::LaneTarget`）；音频线程不做键解析，
    /// 因为那会给 `ParamId` 分配内存，破坏零分配门禁。
    SetAutomation {
        /// 目标轨道。
        track: crate::model::TrackId,
        /// 已解析的自动化目标。
        target: crate::schedule::LaneTarget,
        /// 关键点（拍，升序）。
        points: Vec<crate::model::AutomationPoint>,
    },
    /// 把当前活着的**插件实例**交给宿主预置的回收槽（重建播放器前调用）。
    ///
    /// 结构性变更会重建播放器；实例上挂着两样重建会丢的东西——外部插件的内部补丁，以及
    /// 绑定在实例上的原生界面窗口。收到这条命令时，回调把实例搬进回收槽，重建后的播放器
    /// 再复用它们，于是**改效果链 / 移动片段不会重置乐器配置、也不会关掉插件窗口**。
    /// 属于运行时动作，不写入工程。
    YieldInstances,
}
